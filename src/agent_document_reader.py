"""Qwen-backed, page-by-page reading for user-imported PDF documents.

The reader deliberately separates source material from AI assistance:

* the original page text remains in the existing ``pages`` table;
* each stored reading carries only a source-text fingerprint plus optional
  summary/keywords/facts generated by the configured completion model;
* freshness is checked against the current original page text before a page
  may be used by the Agent;
* no generated summary is ever substituted for the original page text in the
  answer context.

Reading metadata is derived data and is stored as small JSON files under the
configured local data directory.  This avoids changing the frozen Hosted v12
database contract while keeping the local workflow durable and resumable.
"""

