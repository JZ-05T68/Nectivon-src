def get_city_centroids_for_browser() -> list[dict[str, str | float]]:
    """Return city centroids for ephemeral, browser-side geolocation matching.

    The browser receives this static reference dataset and performs nearest-city
    matching locally.  User coordinates therefore never need to be returned to
    Python or persisted by Nectivon.
    """

    return [
        {"province": province, "city": city, "latitude": lat, "longitude": lon}
        for province, city, lat, lon in _CITY_CENTROIDS
    ]


def resolve_city_by_coordinates(latitude: float, longitude: float) -> tuple[str, str] | None:
    """Find the nearest city centroid without persisting coordinates or street addresses."""

    best_match: tuple[str, str] | None = None
    min_distance = float("inf")
    for province, city, lat, lon in _CITY_CENTROIDS:
        # Haversine-approximated euclidean distance for city level matching
        d_lat = latitude - lat
        d_lon = (longitude - lon) * math.cos(math.radians(lat))
        dist = d_lat * d_lat + d_lon * d_lon
        if dist < min_distance:
            min_distance = dist
            best_match = (province, city)
    return best_match


