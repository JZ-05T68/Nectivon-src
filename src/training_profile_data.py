@lru_cache(maxsize=1)
def load_official_schools() -> list[str]:
    """Load the official national higher education institutions list."""

    path = _DATA_DIR / "schools.json"
    if not path.is_file():
        return []
    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    if isinstance(data, list):
        return [str(x).strip() for x in data if str(x).strip()]
    return []


@lru_cache(maxsize=1)
def get_official_school_names_set() -> set[str]:
    """Return a lookup set of all official school names."""

    return set(load_official_schools())


def is_valid_school_name(name: str) -> bool:
    """Verify if a school name strictly exists in the official national database."""

    cleaned = name.strip()
    if not cleaned:
        return False
    return cleaned in get_official_school_names_set()


def search_official_schools(query: str, limit: int = 20) -> list[str]:
    """Search official schools using substring matching, respecting boundaries."""

    q = query.strip()
    if not q:
        return []
    schools = load_official_schools()
    # Match contains
    results: list[str] = []
    # Prefix matches first
    for s in schools:
        if s.startswith(q):
            results.append(s)
            if len(results) >= limit:
                return results
    for s in schools:
        if q in s and s not in results:
            results.append(s)
            if len(results) >= limit:
                break
    return results


